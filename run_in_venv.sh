#!/bin/bash
# Этот скрипт запускает приложение в правильном виртуальном окружении с логированием.

# Получаем директорию, в которой находится сам скрипт
BASE_DIR=$(dirname "$0")

# Путь к активационному скрипту venv
VENV_ACTIVATE="$BASE_DIR/.venv/bin/activate"

# Проверяем, существует ли venv
if [ ! -f "$VENV_ACTIVATE" ]; then
    echo "Ошибка: Виртуальное окружение не найдено. Пожалуйста, запустите 'python3 -m venv .venv' и установите зависимости."
    exit 1
fi

# Активируем venv
source "$VENV_ACTIVATE"

echo "Виртуальное окружение активировано."
echo "Запуск приложения с логированием в app_log.txt..."

# Запускаем приложение через app.py и выводим лог в консоль и в файл
python3 "$BASE_DIR/app.py" 2>&1 | tee "$BASE_DIR/app_log.txt"

# Деактивируем venv после завершения
deactivate
