"""
Модуль для расчета и сглаживания скорости копирования
Использует экспоненциальное скользящее среднее (EMA) для стабильных прогнозов ETA
"""


class SpeedCalculator:
    """
    Класс для расчета сглаженной скорости копирования с использованием EMA
    
    Экспоненциальное скользящее среднее (EMA) обеспечивает плавное сглаживание
    скорости, учитывая историю с экспоненциальным затуханием. Это позволяет
    получать более стабильные и точные прогнозы оставшегося времени.
    """
    
    def __init__(self, alpha: float = 0.2):
        """
        Инициализация калькулятора скорости
        
        :param alpha: Коэффициент сглаживания (0.0-1.0)
                     - Меньшие значения (0.1-0.2): более плавное сглаживание, медленнее реагирует на изменения
                     - Большие значения (0.3-0.5): быстрее реагирует на изменения, но менее стабильно
                     - Рекомендуемое значение: 0.2 (баланс между стабильностью и реактивностью)
        """
        self.alpha = max(0.0, min(1.0, alpha))  # Ограничиваем значение от 0 до 1
        self.ema_speed = 0.0  # Текущее значение EMA скорости
        self.is_initialized = False  # Флаг инициализации
    
    def update(self, current_speed: float) -> float:
        """
        Обновляет EMA скорость на основе текущей скорости
        
        :param current_speed: Текущая скорость в МБ/с
        :return: Сглаженная скорость в МБ/с
        """
        # Игнорируем нулевые или отрицательные скорости (пауза, ошибки)
        if current_speed <= 0:
            # Возвращаем последнее известное значение EMA, не обновляя его
            return self.ema_speed if self.is_initialized else 0.0
        
        if not self.is_initialized:
            # При первой инициализации просто устанавливаем значение
            self.ema_speed = current_speed
            self.is_initialized = True
        else:
            # Применяем формулу EMA: EMA_new = α × current + (1 - α) × EMA_old
            self.ema_speed = self.alpha * current_speed + (1 - self.alpha) * self.ema_speed
        
        return self.ema_speed
    
    def get_speed(self) -> float:
        """
        Возвращает текущее значение сглаженной скорости
        
        :return: Сглаженная скорость в МБ/с
        """
        return self.ema_speed
    
    def reset(self):
        """Сбрасывает состояние калькулятора к начальному"""
        self.ema_speed = 0.0
        self.is_initialized = False

